import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { format } from "date-fns";
import { useRouter } from "expo-router";
import { X } from "phosphor-react-native";
import React, { useState } from "react";
import { Pressable, Switch, View } from "react-native";
import { KeyboardAwareScrollView } from "react-native-keyboard-controller";
import { useSafeAreaInsets } from "react-native-safe-area-context";

import { api } from "@/src/api";
import { DateField, TimeField } from "@/src/components/date-time-field";
import { PtmSession } from "@/src/components/ptm";
import { useToast } from "@/src/components/toast";
import { Button, Card, ChipRow, Field, Header, Segmented, SkeletonList, Txt } from "@/src/components/ui";
import { formatDate } from "@/src/format";
import { radius, spacing, useTheme } from "@/src/theme";

type Opts = { years: { id: string; name: string; is_current: boolean }[]; sections: { section_id: string; label: string; academic_year_id: string }[]; teachers: { teacher_id: string; name: string; section_ids: string[] }[] };
const mins = (t: string) => { const [h, m] = t.split(":").map(Number); return h * 60 + m; };

function Multi({ items, value, onChange, prefix }: { items: { id: string; label: string }[]; value: string[]; onChange: (v: string[]) => void; prefix: string }) {
  return (
    <View style={{ flexDirection: "row", flexWrap: "wrap", gap: spacing.sm }}>
      {items.map((i) => { const on = value.includes(i.id); return <Button key={i.id} small variant={on ? "primary" : "outline"} testID={`${prefix}-${i.id}`} title={i.label} onPress={() => onChange(on ? value.filter((x) => x !== i.id) : [...value, i.id])} />; })}
    </View>
  );
}

export default function NewPtm() {
  const { colors } = useTheme();
  const insets = useSafeAreaInsets();
  const router = useRouter();
  const toast = useToast();
  const qc = useQueryClient();
  const today = format(new Date(), "yyyy-MM-dd");
  const o = useQuery({ queryKey: ["ptm-options"], queryFn: () => api<Opts>("/ptm/options") });
  const [f, setF] = useState({ name: "", year: "", sections: [] as string[], teachers: [] as string[], dates: [] as string[], pick: "", start: "09:00", end: "12:00",
    slot: "10", brk: "0", cap: "1", opensD: "", opensT: "", closesD: "", closesT: "", cancelH: "12", reschH: "12", perChild: "3",
    mode: "physical" as "physical" | "online", location: "", link: "", approval: true });
  const set = (p: Partial<typeof f>) => setF({ ...f, ...p });
  const year = f.year || o.data?.years.find((y) => y.is_current)?.id || o.data?.years[0]?.id || "";
  const secs = (o.data?.sections ?? []).filter((s) => s.academic_year_id === year);
  const teachers = (o.data?.teachers ?? []).filter((t) => t.section_ids.some((s) => f.sections.includes(s)));
  const perTeacher = f.end > f.start ? Math.floor((mins(f.end) - mins(f.start) + Number(f.brk)) / (Number(f.slot) + Number(f.brk))) : 0;
  const err = !f.name.trim() ? "Add a session name" : !f.sections.length ? "Choose at least one section" : !f.teachers.length ? "Choose at least one teacher" : !f.dates.length ? "Add at least one date" : f.end <= f.start ? "End time must be after the start time" : perTeacher < 1 ? "The time window is too short for one meeting" : f.mode === "online" && f.link && !f.link.startsWith("https://") ? "Meeting link must start with https://" : null;
  const save = useMutation({
    mutationFn: (action: "draft" | "publish") => api<PtmSession>("/ptm/sessions", { body: {
      name: f.name, academic_year_id: year, section_ids: f.sections, teacher_ids: f.teachers.filter((t) => teachers.some((x) => x.teacher_id === t)), dates: f.dates,
      start_time: f.start, end_time: f.end, slot_minutes: Number(f.slot), break_minutes: Number(f.brk), capacity: Number(f.cap),
      booking_opens_at: f.opensD ? `${f.opensD}T${f.opensT || "00:00"}:00` : null, booking_closes_at: f.closesD ? `${f.closesD}T${f.closesT || "23:59"}:00` : null,
      cancel_cutoff_hours: Number(f.cancelH), reschedule_cutoff_hours: Number(f.reschH), max_per_child: Number(f.perChild),
      teacher_block_needs_approval: f.approval, mode: f.mode, location: f.location, meeting_link: f.mode === "online" ? f.link : "", action } }),
    onSuccess: (s) => { qc.invalidateQueries({ queryKey: ["ptm-sessions"] }); qc.invalidateQueries({ queryKey: ["calendar"] }); toast.show(s.status === "published" ? "PTM published" : "Draft saved"); router.replace(`/ptm/${s.id}`); },
    onError: (e: Error) => toast.show(e.message, "error"),
  });
  const hours = [0, 6, 12, 24, 48].map((h) => ({ value: String(h), label: h ? `${h}h` : "Any time" }));
  return (
    <View style={{ flex: 1, backgroundColor: colors.surfaceSecondary }}>
      <Header back title="New PTM session" subtitle="Slots are generated by the server on publish" />
      {o.isLoading ? <SkeletonList /> : (
        <KeyboardAwareScrollView bottomOffset={24} contentContainerStyle={{ padding: spacing.lg, paddingBottom: insets.bottom + spacing.xl, gap: spacing.lg }}>
          <Card style={{ gap: spacing.md }}>
            <Field testID="ptm-name-input" label="Session name" value={f.name} onChangeText={(name) => set({ name })} placeholder="e.g. Class 5 Parent–Teacher Meeting" />
            <Txt variant="label" color={colors.onSurfaceTertiary}>Academic year</Txt>
            <View style={{ marginHorizontal: -spacing.lg }}><ChipRow testIDPrefix="ptm-year" value={year} onChange={(y) => set({ year: y, sections: [], teachers: [] })} options={(o.data?.years ?? []).map((y) => ({ value: y.id, label: y.name }))} /></View>
            <Txt variant="label" color={colors.onSurfaceTertiary}>Classes and sections</Txt>
            <Multi prefix="ptm-sec" items={secs.map((s) => ({ id: s.section_id, label: s.label }))} value={f.sections} onChange={(sections) => set({ sections })} />
            <Txt variant="label" color={colors.onSurfaceTertiary}>Participating teachers</Txt>
            {teachers.length ? <Multi prefix="ptm-teacher" items={teachers.map((t) => ({ id: t.teacher_id, label: t.name }))} value={f.teachers} onChange={(t) => set({ teachers: t })} /> : <Txt variant="caption">Choose sections to see their teachers.</Txt>}
          </Card>
          <Card style={{ gap: spacing.md }}>
            <DateField testID="ptm-add-date" label="Add a meeting date" value="" min={today} onChange={(d) => d && !f.dates.includes(d) && set({ dates: [...f.dates, d].sort() })} />
            <View style={{ flexDirection: "row", flexWrap: "wrap", gap: spacing.sm }}>
              {f.dates.map((d) => (
                <Pressable key={d} testID={`ptm-date-${d}`} accessibilityLabel={`Remove ${formatDate(d)}`} onPress={() => set({ dates: f.dates.filter((x) => x !== d) })} style={{ flexDirection: "row", alignItems: "center", gap: 6, minHeight: 36, paddingHorizontal: spacing.md, borderRadius: radius.pill, backgroundColor: colors.brandTertiary }}>
                  <Txt variant="label" raw color={colors.onBrandTertiary}>{formatDate(d)}</Txt><X size={14} color={colors.onBrandTertiary} />
                </Pressable>
              ))}
            </View>
            <View style={{ flexDirection: "row", gap: spacing.sm }}>
              <View style={{ flex: 1 }}><TimeField testID="ptm-start" label="Start time" value={f.start} onChange={(start) => set({ start })} /></View>
              <View style={{ flex: 1 }}><TimeField testID="ptm-end" label="End time" value={f.end} onChange={(end) => set({ end })} error={f.end <= f.start ? "End time must be after the start time" : undefined} /></View>
            </View>
            <Txt variant="label" color={colors.onSurfaceTertiary}>Meeting length (minutes)</Txt>
            <Segmented testIDPrefix="ptm-slot" value={f.slot} onChange={(slot) => set({ slot })} options={["5", "10", "15", "20"].map((v) => ({ value: v, label: v }))} />
            <Txt variant="label" color={colors.onSurfaceTertiary}>Break between meetings (minutes)</Txt>
            <Segmented testIDPrefix="ptm-break" value={f.brk} onChange={(brk) => set({ brk })} options={["0", "5", "10"].map((v) => ({ value: v, label: v }))} />
            <Txt variant="label" color={colors.onSurfaceTertiary}>Families per slot</Txt>
            <Segmented testIDPrefix="ptm-cap" value={f.cap} onChange={(cap) => set({ cap })} options={["1", "2", "3"].map((v) => ({ value: v, label: v }))} />
            <Txt variant="caption" raw testID="ptm-preview">{`${perTeacher} slots per teacher per day · ${perTeacher * f.dates.length * Math.max(1, f.teachers.length)} slots in total`}</Txt>
          </Card>
          <Card style={{ gap: spacing.md }}>
            <Txt variant="overline">Booking window (IST)</Txt>
            <View style={{ flexDirection: "row", gap: spacing.sm }}>
              <View style={{ flex: 1 }}><DateField testID="ptm-opens-date" label="Opens" optional value={f.opensD} onChange={(opensD) => set({ opensD })} /></View>
              <View style={{ flex: 1 }}><TimeField testID="ptm-opens-time" label="At" optional value={f.opensT} onChange={(opensT) => set({ opensT })} /></View>
            </View>
            <View style={{ flexDirection: "row", gap: spacing.sm }}>
              <View style={{ flex: 1 }}><DateField testID="ptm-closes-date" label="Closes" optional value={f.closesD} min={f.opensD || undefined} onChange={(closesD) => set({ closesD })} /></View>
              <View style={{ flex: 1 }}><TimeField testID="ptm-closes-time" label="At" optional value={f.closesT} onChange={(closesT) => set({ closesT })} /></View>
            </View>
            <Txt variant="label" color={colors.onSurfaceTertiary}>Parents may cancel up to</Txt>
            <View style={{ marginHorizontal: -spacing.lg }}><ChipRow testIDPrefix="ptm-cancel-h" value={f.cancelH} onChange={(cancelH) => set({ cancelH })} options={hours} /></View>
            <Txt variant="label" color={colors.onSurfaceTertiary}>Parents may reschedule up to</Txt>
            <View style={{ marginHorizontal: -spacing.lg }}><ChipRow testIDPrefix="ptm-resch-h" value={f.reschH} onChange={(reschH) => set({ reschH })} options={hours} /></View>
            <Txt variant="label" color={colors.onSurfaceTertiary}>Meetings per child</Txt>
            <Segmented testIDPrefix="ptm-per-child" value={f.perChild} onChange={(perChild) => set({ perChild })} options={["1", "2", "3", "5"].map((v) => ({ value: v, label: v }))} />
            <View style={{ flexDirection: "row", alignItems: "center", justifyContent: "space-between", gap: spacing.md }}>
              <Txt variant="body" style={{ flex: 1 }}>Teachers need approval to block slots</Txt>
              <Switch testID="ptm-approval-switch" value={f.approval} onValueChange={(approval) => set({ approval })} />
            </View>
          </Card>
          <Card style={{ gap: spacing.md }}>
            <Segmented testIDPrefix="ptm-mode" value={f.mode} onChange={(mode) => set({ mode })} options={[{ value: "physical", label: "In person" }, { value: "online", label: "Online" }]} />
            <Field testID="ptm-location-input" label={f.mode === "online" ? "Meeting details (optional)" : "Room / location"} value={f.location} onChangeText={(location) => set({ location })} placeholder="e.g. Classroom 5A" />
            {f.mode === "online" ? <Field testID="ptm-link-input" label="Meeting link (shown only to booked parents)" value={f.link} onChangeText={(link) => set({ link })} autoCapitalize="none" placeholder="Paste the https meeting link" /> : null}
          </Card>
          {err ? <Txt variant="caption" raw color={colors.error} testID="ptm-form-error">{err}</Txt> : null}
          <View style={{ flexDirection: "row", gap: spacing.sm }}>
            <Button style={{ flex: 1 }} variant="outline" testID="ptm-save-draft" title="Save draft" disabled={!!err} loading={save.isPending && save.variables === "draft"} onPress={() => save.mutate("draft")} />
            <Button style={{ flex: 1 }} testID="ptm-publish" title="Publish" disabled={!!err} loading={save.isPending && save.variables === "publish"} onPress={() => save.mutate("publish")} />
          </View>
        </KeyboardAwareScrollView>
      )}
    </View>
  );
}
